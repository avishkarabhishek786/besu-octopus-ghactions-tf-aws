#!/usr/bin/env bash
# =============================================================================
# apply-tenancy.sh — create the namespace the cloud team would have allotted us.
# -----------------------------------------------------------------------------
# RUN FROM THE RUNNER. In the strict profile the cluster's API endpoint is
# private, so a laptop cannot reach it — the same constraint the platform lives
# with (D-34), and reproducing it is part of the point.
#
# WHY THIS IS A SCRIPT AND NOT TERRAFORM
#   Fidelity. The cloud team hands us a namespace; they do not Terraform one
#   into our state. See terraform/tenancy.tf for the full reasoning.
#
# WHAT IT APPLIES
#   manifests/tenancy.yaml, rendered by `terraform apply` in terraform/. Two
#   namespaces, a ResourceQuota, a StorageClass, and (strict only) the Role that
#   `edit` does not give us.
#
# Usage:
#   scripts/apply-tenancy.sh            # apply
#   scripts/apply-tenancy.sh --diff     # show what would change, change nothing
#   scripts/apply-tenancy.sh --delete   # remove it again
# =============================================================================
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
MANIFEST="$ROOT/manifests/tenancy.yaml"
MODE="apply"
case "${1:-}" in
  --diff)   MODE="diff" ;;
  --delete) MODE="delete" ;;
  "")       ;;
  *) echo "usage: apply-tenancy.sh [--diff|--delete]" >&2; exit 2 ;;
esac

log() { printf '[%s] %s\n' "$(date -u +%H:%M:%S)" "$*"; }
die() { printf '[ERROR] %s\n' "$*" >&2; exit 1; }

command -v kubectl >/dev/null || die "kubectl is required (and this must run from the runner)."
[[ -r "$MANIFEST" ]] || die "no rendered manifest at $MANIFEST — run 'terraform apply' in $ROOT/terraform first."

# Refuse to apply a manifest whose YAML does not parse. The first version of
# tenancy.tf rendered mis-indented pod-security labels, and the failure would
# otherwise have surfaced as a kubectl parser error that reads like a platform
# problem. Validate before touching the cluster.
log "validating $MANIFEST"
kubectl apply --dry-run=client -f "$MANIFEST" >/dev/null \
  || die "the rendered manifest is not valid — this is a mimic bug, not a cluster problem. Re-render it."

PROFILE="$(sed -n 's/^# Fidelity profile: //p;s/^# GENERATED by mimic_eks. Profile: //p' "$MANIFEST" | head -1)"
log "profile: ${PROFILE:-unknown}"

case "$MODE" in
  diff)
    log "kubectl diff (nothing is changed)"
    kubectl diff -f "$MANIFEST" || true   # diff exits 1 when there IS a difference
    ;;
  delete)
    log "deleting the tenancy objects"
    kubectl delete -f "$MANIFEST" --ignore-not-found
    log "SUCCESS. The cluster itself is still up — tear it down with terraform destroy."
    ;;
  apply)
    log "applying"
    kubectl apply -f "$MANIFEST"
    echo
    log "what the platform will now see:"
    kubectl get ns -l 'kubernetes.io/metadata.name' --show-labels 2>/dev/null | head -1 || true
    for ns in $(grep -oE '^  name: [a-z0-9-]+' "$MANIFEST" | awk '{print $2}' | sort -u); do
      kubectl get ns "$ns" --show-labels --no-headers 2>/dev/null | sed 's/^/    /' || true
      kubectl -n "$ns" get resourcequota --no-headers 2>/dev/null | sed 's/^/      quota: /' || true
    done
    kubectl get storageclass --no-headers 2>/dev/null \
      | awk '{printf "    sc: %s  %s\n", $1, $0}' | cut -c1-120 || true
    echo
    if [[ "$PROFILE" == "hostile" ]]; then
      log "REMINDER: this is the hostile profile. Now run the platform's preflights and"
      log "          CONFIRM THEY FAIL, each citing its requirement number:"
      log "            sbsa_besu/scripts/preflight/verify-cluster.sh -n <ledger-ns> -s <sc>"
      log "            sbsa_besu/scripts/preflight/verify-admission.sh -n <ledger-ns> -f <rendered.yaml>"
      log "          A pass here is a bug in the check, not good news."
    fi
    log "SUCCESS."
    ;;
esac
